"""TEAR applied to the released top-15 lists of TimeR4's fine-tuned retriever (MultiTQ), LLM-free Hit@1.

The released lists carry no scores, so each candidate gets the rank score 1 - 0.04 * rank (1.00 for rank 0, 0.44 for
rank 14; a lambda = 0.8 penalty then moves a top candidate about five places down, as a cosine similarity of 0.8 would).
The rules read the same inputs as in the main setting (rule v2 labels, grounded anchors, equal window, exact topic
matching, date parser v2). 19 of the 54,584 lists contain an unmapped string (0.03%); it is replaced by the list's last
mapped fact so that every list has 15 candidates. Coverage@15 is that of the released lists for every reranker (the set
does not change); only the order, and therefore the LLM-free answer read off the top-1 fact, changes.

  .venv/bin/python -I scripts/30_tear_on_timer4_lists.py
      -> results/timer4_lists_tear.md, results/timer4_lists_tear_{llmfree,significance}.csv
"""
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tear.data.candidates import CandidatePool  # noqa: E402
from tear.evaluation.hits import llmfree_rows, summarize_llmfree  # noqa: E402
from tear.rerank.core import PROMOTE, rerank  # noqa: E402
from tear.rerank.features import build_features  # noqa: E402
from tear.utils.io import load_json  # noqa: E402

RERANKERS = ["none", "hardwindow", "atc", "tr", "tear", "tear_window"] + PROMOTE
PAIRS = [("none", "tear_window"), ("none", "hardwindow"), ("hardwindow", "tear_window"), ("none", "tear"),
         ("none", "atc"), ("none", "tr"), ("tear_window", "tear_window_promote")]


def sig(a, b):
    a = np.asarray(a, bool); b = np.asarray(b, bool); rng = np.random.default_rng(0)
    b01 = int((~a & b).sum()); b10 = int((a & ~b).sum())
    p = math.erfc(math.sqrt(((abs(b01 - b10) - 1) ** 2 / max(1, b01 + b10)) / 2)) if b01 + b10 else 1.0
    d = b.astype(float) - a.astype(float); bs = d[rng.integers(0, len(d), (10000, len(d)))].mean(1)
    return d.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5), p, b01, b10


def main():
    pool = CandidatePool("multitq_orig", 1000)
    ids = np.array([q["timer4_top15_ids"] for q in pool.qs], np.int64)
    fixed = 0
    for row in ids:
        bad = row < 0
        if bad.any():
            good = row[~bad]
            row[bad] = good[-1] if len(good) else 0; fixed += 1
    pool.ids = ids.astype(np.int32)
    pool.sims = np.tile((1.0 - 0.04 * np.arange(15)).astype(np.float32), (len(pool.qs), 1))
    pool.N = 15
    slots = load_json(pool.d / "slots_rule_v2.json")
    F = build_features(pool, slots, None, "any", "exact", "v2", load_json(pool.d / "anchors.json"), True)
    keys = [pool.key(q) for q in pool.qs]
    qby = {pool.key(q): q for q in pool.qs}
    facts = np.load(pool.d / "facts.npz"); voc = load_json(pool.d / "vocab.json")
    per = {}
    for name in RERANKERS:
        perm = rerank(name, pool.sims, F, 0.8, 0.8)
        top1 = np.take_along_axis(pool.ids, perm[:, :1], axis=1)[:, 0]
        r = llmfree_rows(top1, keys, qby, slots, facts, voc["entities"], voc["timestamps"], name)
        per[name] = pd.DataFrame(r, columns=["reranker", "qtype", "qlabel", "answer_type", "exact", "lenient"])
    df = pd.concat(per.values(), ignore_index=True)
    res = summarize_llmfree(df)
    res.insert(1, "candidate_lists", "TimeR4 released top-15 (fine-tuned retriever)")
    # main-pool values for reference (same tag)
    main_tbl = pd.read_csv(ROOT / "results" / "multitq_orig_llmfree_hit1_rule_v2_ground_exact_anydate.csv")
    main_tbl.insert(1, "candidate_lists", "off-the-shelf retriever top-1000 (main setting)")
    sigs = []
    for base, s in PAIRS:
        a, b = per[base], per[s]
        groups = [("all", np.ones(len(a), bool))] + [(t, (a.qtype == t).values) for t in sorted(a.qtype.unique())]
        for g, m in groups:
            d, lo, hi, p, g01, g10 = sig(a.exact.values[m], b.exact.values[m])
            sigs.append({"baseline": base, "setting": s, "group": g, "n": int(m.sum()), "base_hit1": a.exact.values[m].mean(),
                         "var_hit1": b.exact.values[m].mean(), "diff": d, "ci_low": lo, "ci_high": hi, "mcnemar_p": p,
                         "gains": g01, "losses": g10})
    SG = pd.DataFrame(sigs)
    out = ROOT / "results"
    res.to_csv(out / "timer4_lists_tear_llmfree.csv", index=False); SG.to_csv(out / "timer4_lists_tear_significance.csv", index=False)
    cols = ["reranker", "n", "exact_all", "exact_equal", "exact_before_after", "exact_first_last", "exact_equal_multi",
            "exact_after_first", "exact_before_last", "exact_entity", "exact_time"]
    lines = ["# TEAR on the released top-15 lists of TimeR4's fine-tuned retriever (LLM-free Hit@1, MultiTQ test set)", "",
             f"Generated by `scripts/30_tear_on_timer4_lists.py`. Rank scores 1 - 0.04 * rank; {fixed} lists had an unmapped "
             "string replaced by the list's last mapped fact. Same rule inputs as the main setting "
             "(rule_v2_ground_exact_anydate).", "",
             "## On TimeR4's lists", "", res[cols].to_markdown(index=False, floatfmt=".4f"), "",
             "## Main setting (off-the-shelf retriever top-1000), for reference", "",
             main_tbl[main_tbl.reranker.isin(RERANKERS)][cols].to_markdown(index=False, floatfmt=".4f"), "",
             "## Paired differences on TimeR4's lists", ""]
    g = SG.copy(); g["mcnemar_p"] = g.mcnemar_p.map(lambda v: f"{v:.1e}")
    lines += [g.to_markdown(index=False, floatfmt=".4f"), ""]
    (out / "timer4_lists_tear.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
